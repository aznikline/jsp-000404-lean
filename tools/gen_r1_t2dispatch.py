#!/usr/bin/env python3
"""Emit Jsp000404/R1DispatchT2.lean — the R1 T2 (t = 7, Phi = 21) geometric
dispatch layer.

Structure:
  1. `r1_phi21_unique_defect4` — potential bookkeeping: t = 7 R1 profile
     (sat anchor v, defect-2 row a, tails >= 3, Phi = 21) forces exactly one
     defect-4 tail z and four defect-3 tails.
  2. `r1t2_u{key}` — one exclusion helper per T2 spec shape (14): obtain row
     signatures via n7_row{1,2}_exists and call the matching r1cert.
  3. `r1_seven_phi21_terminal` — build the SatChart, map the defect-2 row a
     and the defect-4 row z to ranks ra, rz via n7σ, then `fin_cases` over
     all 30 (ra, rz) assignments and dispatch to the covering spec helper.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'Jsp000404', 'R1DispatchT2.lean')

SPECS = json.load(open(os.path.join(ROOT, 'tools', 'r1_specs.json')))['T2']
# u-key -> list[(rank, kind)]  (kind in {'s1','s2'})

CERT_FILE = {}
CERT_NAME = {}
for uk, spec in SPECS.items():
    toks = [f"{k}a{r}" for r, k in spec]  # rank-sorted in spec order
    name = 'r1cert_T2_' + '_'.join(toks)
    CERT_NAME[uk] = name
    CERT_FILE[uk] = 'R1CertT2_' + '_'.join(
        f"{k[1]}{r}" for r, k in spec)  # kind digit + rank, e.g. 20_11_13_14

# ---- (ra, rz) -> spec u-key coverage table ------------------------------
COV = {}
for a in range(6):
    for z in range(6):
        if z == a:
            continue
        scored = {a: 's2', **{r: 's1' for r in range(6) if r != a and r != z}}
        cands = [uk for uk, spec in SPECS.items()
                 if all(scored.get(r) == k for r, k in spec)]
        assert cands, f'uncovered assignment {(a, z)}'
        COV[(a, z)] = cands[0]

CERT_IMPORTS = sorted(set(CERT_FILE.values()))
MODS = [f'Jsp000404.{m}' for m in CERT_IMPORTS]

L = []
emit = L.append
emit('import Jsp000404.S7N7Core')
for m in MODS:
    emit(f'import {m}')
emit('import Jsp000404.FivePointCapacity')
emit('import Jsp000404.ConeCorridor')
emit('')
emit('/-! **R1 T2 dispatch layer (generated).**  Excludes a seven-centre')
emit('`n = 4` legal R1 configuration with saturated anchor `v`, defect-`2`')
emit('row `a`, all other tails of defect `≥ 3`, and potential `Φ = 21`.')
emit('The potential ledger forces a unique defect-`4` tail `z`; the θ-ranks')
emit('`(ra, rz)` of `(a, z)` enumerate 30 assignments, each covered by a T2')
emit('UNSAT spec.')
emit('')
emit('Generated by `tools/gen_r1_t2dispatch.py`. -/')
emit('')
emit('namespace Jsp404')
emit('')
emit('/-! ### Potential bookkeeping -/')
emit('')
emit('/-- `Φ = 21` at `t = 7` in the R1 profile (saturated `v`, defect-`2` `a`,')
emit('every other tail of defect `≥ 3`) forces a unique defect-`4` tail `z`: the')
emit('five tails contribute `2^(4−d_w) ∈ {1, 2}` summing to `9 = 4·2 + 1`, so')
emit('exactly one tail has defect `4` and the remaining four have defect `3`. -/')
emit('theorem r1_phi21_unique_defect4')
emit('    (o : Orientation ℝ Plane₂ (Fin 2)) (e : Plane₂) (he : e ≠ 0)')
emit('    {lam : ℝ} (hlam : 0 < lam) (hn : Nat.floor (Real.pi / lam) = 4)')
emit('    {c : Fin 7 → Plane₂} (hleg : Section4Legality c lam)')
emit('    {v a : Fin 7} (hva : v ≠ a)')
emit('    (hsat : rowDefect 4 lam (directionRow o e c v) = 1)')
emit('    (hda : rowDefect 4 lam (directionRow o e c a) = 2)')
emit('    (htail : ∀ w : Fin 7, w ≠ v → w ≠ a →')
emit('      3 ≤ rowDefect 4 lam (directionRow o e c w))')
emit('    (hF : potential lam (directionRows o e c) = 21) :')
emit('    ∃ z : Fin 7, z ≠ v ∧ z ≠ a ∧')
emit('      rowDefect 4 lam (directionRow o e c z) = 4 ∧')
emit('      ∀ w : Fin 7, w ≠ v → w ≠ a → w ≠ z →')
emit('        rowDefect 4 lam (directionRow o e c w) = 3 := by')
emit('  classical')
emit('  have hcells : ∀ w : Fin 7,')
emit('      rowCells lam (directionRow o e c w) ≤ 4 :=')
emit('    fun w => rowCells_directionRow_le_of_floor_eq o e c hlam w (by omega) hn')
emit('  have hsd : ∀ w : Fin 7, rowScore lam (directionRow o e c w) =')
emit('      4 - rowDefect 4 lam (directionRow o e c w) :=')
emit('    fun w => rowScore_eq_sub_defect lam hlam 4 _ (hcells w)')
emit('  have hsum : (∑ w : Fin 7,')
emit('      2 ^ rowScore lam (directionRow o e c w)) = 21 := hF')
emit('  have hfv : 2 ^ rowScore lam (directionRow o e c v) = 8 := by')
emit('    rw [hsd v, hsat] <;> norm_num')
emit('  have hfa : 2 ^ rowScore lam (directionRow o e c a) = 4 := by')
emit('    rw [hsd a, hda] <;> norm_num')
emit('  have hm : ∀ {w : Fin 7},')
emit('      w ∈ (Finset.univ.erase v).erase a → w ≠ v ∧ w ≠ a := fun hw =>')
emit('    ⟨(Finset.mem_erase.mp (Finset.mem_erase.mp hw).2).1,')
emit('     (Finset.mem_erase.mp hw).1⟩')
emit('  have hcard : ((Finset.univ.erase v).erase a).card = 5 := by')
emit('    rw [Finset.card_erase_of_mem')
emit('        (Finset.mem_erase.mpr ⟨hva.symm, Finset.mem_univ a⟩),')
emit('        Finset.card_erase_of_mem (Finset.mem_univ v), Finset.card_univ, Fintype.card_fin] <;> norm_num')
emit('  have h34 : ∀ w : Fin 7, w ≠ v → w ≠ a →')
emit('      rowDefect 4 lam (directionRow o e c w) = 3 ∨')
emit('      rowDefect 4 lam (directionRow o e c w) = 4 := by')
emit('    intro w hwv hwa')
emit('    have h1 := htail w hwv hwa')
emit('    have h2 := rowDefect_le lam hlam 4 _ (hcells w)')
emit('    rcases lt_or_ge (rowDefect 4 lam (directionRow o e c w)) 4')
emit('      with hlt | hge')
emit('    · left; omega')
emit('    · right; omega')
emit('  have hf12 : ∀ w ∈ (Finset.univ.erase v).erase a,')
emit('      2 ^ rowScore lam (directionRow o e c w) = 1 ∨')
emit('      2 ^ rowScore lam (directionRow o e c w) = 2 := by')
emit('    intro w hw')
emit('    obtain ⟨hwv, hwa⟩ := hm hw')
emit('    rcases h34 w hwv hwa with h | h')
emit('    · right; rw [hsd w, h] <;> norm_num')
emit('    · left; rw [hsd w, h] <;> norm_num')
emit('  have e1 : ∑ x ∈ Finset.univ.erase v,')
emit('      2 ^ rowScore lam (directionRow o e c x) +')
emit('      2 ^ rowScore lam (directionRow o e c v) =')
emit('      ∑ w : Fin 7, 2 ^ rowScore lam (directionRow o e c w) :=')
emit('    Finset.sum_erase_add _ _ (Finset.mem_univ v)')
emit('  have e2 : ∑ x ∈ (Finset.univ.erase v).erase a,')
emit('      2 ^ rowScore lam (directionRow o e c x) +')
emit('      2 ^ rowScore lam (directionRow o e c a) =')
emit('      ∑ x ∈ Finset.univ.erase v,')
emit('        2 ^ rowScore lam (directionRow o e c x) :=')
emit('    Finset.sum_erase_add _ _')
emit('      (Finset.mem_erase.mpr ⟨hva.symm, Finset.mem_univ a⟩)')
emit('  have hsumT : ∑ w ∈ (Finset.univ.erase v).erase a,')
emit('      2 ^ rowScore lam (directionRow o e c w) = 9 := by')
emit('    omega')
emit('  obtain ⟨z, hzT, hfz⟩ : ∃ z ∈ (Finset.univ.erase v).erase a,')
emit('      2 ^ rowScore lam (directionRow o e c z) = 1 := by')
emit('    by_contra hcon')
emit('    push_neg at hcon')
emit('    have hall2 : ∀ w ∈ (Finset.univ.erase v).erase a,')
emit('        2 ^ rowScore lam (directionRow o e c w) = 2 :=')
emit('      fun w hw => (hf12 w hw).resolve_left (hcon w hw)')
emit('    have hcongr : ∑ w ∈ (Finset.univ.erase v).erase a,')
emit('        2 ^ rowScore lam (directionRow o e c w) = 10 := by')
emit('      rw [Finset.sum_congr rfl hall2, Finset.sum_const, hcard,')
emit('        smul_eq_mul]')
emit('    omega')
emit('  obtain ⟨hzv, hza⟩ := hm hzT')
emit('  have hdz : rowDefect 4 lam (directionRow o e c z) = 4 := by')
emit('    rcases h34 z hzv hza with h | h')
emit('    · exfalso; rw [hsd z, h] at hfz')
emit('      exact absurd hfz (by decide)')
emit('    · exact h')
emit('  refine ⟨z, hzv, hza, hdz, ?_⟩')
emit('  intro w hwv hwa hwz')
emit('  have hwT : w ∈ (Finset.univ.erase v).erase a :=')
emit('    Finset.mem_erase.mpr ⟨hwa,')
emit('      Finset.mem_erase.mpr ⟨hwv, Finset.mem_univ w⟩⟩')
emit('  rcases h34 w hwv hwa with h | h')
emit('  · exact h')
emit('  · exfalso')
emit('    have hfw : 2 ^ rowScore lam (directionRow o e c w) = 1 := by')
emit('      rw [hsd w, h] <;> norm_num')
emit('    have hwTz : w ∈ ((Finset.univ.erase v).erase a).erase z :=')
emit('      Finset.mem_erase.mpr ⟨hwz, hwT⟩')
emit('    have e3 : ∑ x ∈ ((Finset.univ.erase v).erase a).erase z,')
emit('        2 ^ rowScore lam (directionRow o e c x) +')
emit('        2 ^ rowScore lam (directionRow o e c z) =')
emit('        ∑ x ∈ (Finset.univ.erase v).erase a,')
emit('          2 ^ rowScore lam (directionRow o e c x) :=')
emit('      Finset.sum_erase_add _ _ hzT')
emit('    have e4 :')
emit('        ∑ x ∈ (((Finset.univ.erase v).erase a).erase z).erase w,')
emit('          2 ^ rowScore lam (directionRow o e c x) +')
emit('        2 ^ rowScore lam (directionRow o e c w) =')
emit('        ∑ x ∈ ((Finset.univ.erase v).erase a).erase z,')
emit('          2 ^ rowScore lam (directionRow o e c x) :=')
emit('      Finset.sum_erase_add _ _ hwTz')
emit('    have hcard2 :')
emit('        ((((Finset.univ.erase v).erase a).erase z).erase w).card = 3 := by')
emit('      rw [Finset.card_erase_of_mem hwTz,')
emit('          Finset.card_erase_of_mem hzT, hcard]')
emit('    have hbound :')
emit('        ∑ x ∈ (((Finset.univ.erase v).erase a).erase z).erase w,')
emit('          2 ^ rowScore lam (directionRow o e c x) ≤ 6 := by')
emit('      calc ∑ x ∈ (((Finset.univ.erase v).erase a).erase z).erase w,')
emit('            2 ^ rowScore lam (directionRow o e c x)')
emit('          ≤ ((((Finset.univ.erase v).erase a).erase z).erase w).card')
emit('              • 2 :=')
emit('            Finset.sum_le_card_nsmul _ _ _ (fun x hx => by')
emit('              have hxT := Finset.mem_of_mem_erase')
emit('                (Finset.mem_of_mem_erase hx)')
emit('              rcases hf12 x hxT with hh | hh <;> omega)')
emit('        _ = 6 := by rw [hcard2, smul_eq_mul]')
emit('    omega')
emit('')
emit('/-! ### Per-spec exclusion helpers -/')
emit('')

# ---- helpers ------------------------------------------------------------
for uk in sorted(SPECS, key=lambda k: int(k[1:])):
    spec = SPECS[uk]
    emit(f'/-- Spec `{uk}` excluded: rows ' +
         ', '.join(f'`{k}` at rank `{r}`' for r, k in spec) + '. -/')
    emit(f'theorem r1t2_{uk} (C : SatChart o e 4 lam c v theta)')
    us = ' '.join(f'u{r}' for r, _ in spec)
    emit(f'    {{{us} : Fin 6}}')
    for r, k in spec:
        emit(f'    (h{r} : n7σ C {r} = u{r})')
    for r, k in spec:
        dv = '2' if k == 's2' else '3'
        emit(f'    (hd{r} : rowDefect 4 lam')
        emit(f'      (directionRow o e c (v.succAbove u{r})) = {dv})')
    emit('    : False := by')
    for r, k in spec:
        xv = ', '.join(f'x{r}{i}' for i in range(5))
        fn = 'n7_row2_exists' if k == 's2' else 'n7_row1_exists'
        emit(f'  obtain ⟨{xv}, ho{r}, hs{r}, hp{r}⟩ := {fn} C h{r} hd{r}')
    args = ' '.join(
        f'ho{r} hs{r} (n7_row_perm C hp{r})' for r, _ in spec)
    emit(f'  exact R2N4.{CERT_NAME[uk]} (n7model C) {args}')
    emit('')

# ---- main dispatch --------------------------------------------------------
emit('/-! ### Terminal dispatch -/')
emit('')
emit('/-- **R1 T2 terminal exclusion.**  A seven-centre `n = 4` legal')
emit('configuration with saturated anchor `v`, defect-`2` row `a`, tails of')
emit('defect `≥ 3` and `Φ = 21` is impossible: bookkeeping gives a unique')
emit('defect-`4` tail `z`, and each of the 30 θ-rank assignments `(ra, rz)` is')
emit('excluded by a T2 spec certificate. -/')
emit('theorem r1_seven_phi21_terminal')
emit('    (o : Orientation ℝ Plane₂ (Fin 2)) (e : Plane₂) (he : e ≠ 0)')
emit('    {lam : ℝ} (hlam : 0 < lam) (hn : Nat.floor (Real.pi / lam) = 4)')
emit('    {c : Fin 7 → Plane₂} (hleg : Section4Legality c lam)')
emit('    {v a : Fin 7} (hva : v ≠ a)')
emit('    (hsat : rowDefect 4 lam (directionRow o e c v) = 1)')
emit('    (hda : rowDefect 4 lam (directionRow o e c a) = 2)')
emit('    (htail : ∀ w : Fin 7, w ≠ v → w ≠ a →')
emit('      3 ≤ rowDefect 4 lam (directionRow o e c w))')
emit('    (hF : potential lam (directionRows o e c) = 21) : False := by')
emit('  classical')
emit('  obtain ⟨z, hzv, hza, hdz, hrest⟩ :=')
emit('    r1_phi21_unique_defect4 o e he hlam hn hleg hva hsat hda htail hF')
emit('  obtain ⟨e\', he\', theta, htheta⟩ :=')
emit('    saturated_ray_window o e he (by omega) (by omega) hlam hn hleg v hsat')
emit('  have C : SatChart o e\' 4 lam c v theta :=')
emit('    ⟨he\', by omega, hlam, hn, hleg, htheta⟩')
emit('  have href : ∀ x : Fin 7,')
emit('      rowDefect 4 lam (directionRow o e\' c x) =')
emit('        rowDefect 4 lam (directionRow o e c x) := fun x =>')
emit('    rowDefect_directionRow_reference_eq o e\' e he\' he c hleg.inj x')
emit('      hlam (by omega) hn')
emit('  obtain ⟨ua, hua⟩ := Fin.exists_succAbove_eq hva.symm')
emit('  obtain ⟨uz, huz⟩ := Fin.exists_succAbove_eq hzv')
emit('  obtain ⟨ra, hra⟩ := (n7σ_bijective C).surjective ua')
emit('  obtain ⟨rz, hrz⟩ := (n7σ_bijective C).surjective uz')
emit('  have hza_idx : uz ≠ ua := fun h => hza (by rw [← huz, h, hua])')
emit('  have hrz_ne : rz ≠ ra := fun h =>')
emit('    hza_idx (by rw [← hrz, ← hra, h])')
emit('  have hd2 : rowDefect 4 lam')
emit('      (directionRow o e\' c (v.succAbove ua)) = 2 := by')
emit('    rw [hua, href]; exact hda')
emit('  have hd3 : ∀ u : Fin 6, u ≠ ua → u ≠ uz →')
emit('      rowDefect 4 lam')
emit('        (directionRow o e\' c (v.succAbove u)) = 3 := by')
emit('    intro u hna hnz')
emit('    have hwv : v.succAbove u ≠ v := Fin.succAbove_ne v u')
emit('    have hwa : v.succAbove u ≠ a := fun hh =>')
emit('      hna (Fin.succAbove_right_injective (hh.trans hua.symm))')
emit('    have hwz : v.succAbove u ≠ z := fun hh =>')
emit('      hnz (Fin.succAbove_right_injective (hh.trans huz.symm))')
emit('    rw [href]; exact hrest _ hwv hwa hwz')
emit('  have hd3r : ∀ r : Fin 6, n7σ C r ≠ ua → n7σ C r ≠ uz →')
emit('      rowDefect 4 lam')
emit('        (directionRow o e\' c (v.succAbove (n7σ C r))) = 3 :=')
emit('    fun r h1 h2 => hd3 _ h1 h2')
emit('  fin_cases ra')

for a in range(6):
    emit('  · fin_cases rz')
    for z in range(6):
        if z == a:
            emit('    · exact absurd rfl hrz_ne')
            continue
        uk = COV[(a, z)]
        spec = SPECS[uk]
        s1ranks = [r for r, k in spec if k == 's1']
        for i, r in enumerate(s1ranks):
            pre = '·' if i == 0 else ' '
            emit(f'    {pre} have h{r}na : n7σ C {r} ≠ ua := fun hh =>')
            emit('        absurd ((n7σ_bijective C).injective')
            emit(f'          (hh.trans hra.symm)) (by decide)')
            emit(f'      have h{r}nz : n7σ C {r} ≠ uz := fun hh =>')
            emit('        absurd ((n7σ_bijective C).injective')
            emit(f'          (hh.trans hrz.symm)) (by decide)')
        # build the call: h-args then hd-args in rank order
        hargs = []
        hdargs = []
        for r, k in spec:
            if k == 's2':
                hargs.append('hra')
                hdargs.append('hd2')
            else:
                hargs.append('rfl')
                hdargs.append(f'(hd3r {r} h{r}na h{r}nz)')
        emit(f'      exact r1t2_{uk} C ' + ' '.join(hargs) + ' ' +
             ' '.join(hdargs))

emit('')
emit('end Jsp404')

with open(OUT, 'w') as fh:
    fh.write('\n'.join(L) + '\n')
print(f'wrote {OUT}: {len(L)} lines')
print('cert map:')
for uk in sorted(SPECS, key=lambda k: int(k[1:])):
    print(f'  {uk}: {CERT_NAME[uk]} <- {CERT_FILE[uk]}')
